export type MockPatientRow = NewPatientRow & { created_at: Date };

// Checks every mock patient with the app's own rules and turns it into a row to insert.
// Throws, naming the record, if any patient is invalid, so bad data is never seeded.
export function buildMockPatientRows(now: Date): MockPatientRow[] {
  return MOCK_PATIENTS.map((mockPatient, index) => {
    const result = createPatientSchema.safeParse(mockPatient.patient);
    if (!result.success) {
      const fieldErrors = JSON.stringify(z.flattenError(result.error).fieldErrors);
      throw new Error(`Mock patient ${index + 1} (${mockPatient.edgeCase}) is invalid: ${fieldErrors}`);
    }
    const addedAt = new Date(now.getTime() - mockPatient.addedHoursAgo * 60 * 60 * 1000);
    return { ...toNewPatientRow(result.data), created_at: addedAt };
  });
}
